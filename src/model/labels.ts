// Label and annotation keys Flux and the Flux Operator put on the objects they manage.
// Sources are cited in docs/DECISIONS.md ("Ownership labels and annotations").

/** kustomize-controller labels every object it applies with the Kustomization's name and namespace. */
export const KUSTOMIZE_NAME = 'kustomize.toolkit.fluxcd.io/name';
export const KUSTOMIZE_NAMESPACE = 'kustomize.toolkit.fluxcd.io/namespace';

/** helm-controller labels every object Helm renders with the HelmRelease's name and namespace. */
export const HELM_NAME = 'helm.toolkit.fluxcd.io/name';
export const HELM_NAMESPACE = 'helm.toolkit.fluxcd.io/namespace';

/** The Flux Operator labels objects generated by a ResourceSet. */
export const RESOURCESET_NAME = 'resourceset.fluxcd.controlplane.io/name';
export const RESOURCESET_NAMESPACE = 'resourceset.fluxcd.controlplane.io/namespace';

/** `disabled` stops kustomize-controller from changing the object (drift is left alone). */
export const KUSTOMIZE_RECONCILE = 'kustomize.toolkit.fluxcd.io/reconcile';
/** `disabled` stops kustomize-controller from deleting the object (garbage collection or deletion). */
export const KUSTOMIZE_PRUNE = 'kustomize.toolkit.fluxcd.io/prune';
/** The Flux Operator's equivalents, honoured for FluxInstance and ResourceSet inventories. */
export const OPERATOR_RECONCILE = 'fluxcd.controlplane.io/reconcile';
export const OPERATOR_PRUNE = 'fluxcd.controlplane.io/prune';
/** Helm keeps objects with this annotation set to `keep` on uninstall. */
export const HELM_RESOURCE_POLICY = 'helm.sh/resource-policy';

/** The FluxInstance that installed an object (Flux Operator). */
export const FLUXINSTANCE_NAME = 'fluxcd.controlplane.io/name';
export const FLUXINSTANCE_NAMESPACE = 'fluxcd.controlplane.io/namespace';

/** The docs spell the value `disabled` and `Disabled`; compare without case. */
function isDisabled(value: string | undefined): boolean {
  return value !== undefined && value.toLowerCase() === 'disabled';
}

export function isPruneDisabled(annotations: Record<string, string> | undefined): boolean {
  if (annotations === undefined) return false;
  return isDisabled(annotations[KUSTOMIZE_PRUNE]) || isDisabled(annotations[OPERATOR_PRUNE]);
}

export function isReconcileDisabled(annotations: Record<string, string> | undefined): boolean {
  if (annotations === undefined) return false;
  return isDisabled(annotations[KUSTOMIZE_RECONCILE]) || isDisabled(annotations[OPERATOR_RECONCILE]);
}

export function isHelmKept(annotations: Record<string, string> | undefined): boolean {
  return annotations?.[HELM_RESOURCE_POLICY] === 'keep';
}
